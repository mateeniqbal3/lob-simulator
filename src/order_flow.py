"""Stochastic order-flow model (PROJECT.md section 6; parameters in DECISIONS.md ADR-001).

A zero-intelligence model in the spirit of Smith et al. (2003) and
Cont, Stoikov & Talreja (2010), kept deliberately simple:

* **Limit orders** arrive on each side as a Poisson process with rate
  ``limit_rate``. A buy limit is placed ``d`` ticks below the best ask (a sell
  limit ``d`` ticks above the best bid), with ``d`` drawn from
  ``P(d) ∝ d^-distance_alpha`` on ``1..max_distance``. Because ``d >= 1`` a
  limit order never crosses, so all aggressive flow comes from market orders.
  If the opposite side is empty, the last observed opposite quote is used.
* **Market orders** arrive on each side as a Poisson process with rate
  ``market_rate``.
* **Cancellations**: every resting order is cancelled independently at rate
  ``cancel_rate`` (exponential lifetime), so the total cancellation intensity
  is ``cancel_rate * number_of_resting_orders``.
* **Sizes**: limit orders are ``lot * U{1..limit_max_lots}``; market orders are
  ``lot * Geometric(market_size_p)`` (support 1, 2, ...).

Events are generated by exact simulation of the competing Poisson clocks
(Gillespie's algorithm). Rates may be modified over time by a
``RateSchedule`` (see ``event_injection.py``); at a schedule breakpoint the
clock is restarted, which is exact because exponential waiting times are
memoryless and ensures that nothing before a breakpoint depends on what the
schedule does after it.

The generator is state-dependent (prices are set relative to the current
quotes, cancellations pick among currently resting orders), so it runs its
own ``MatchingEngine`` alongside and only ever reads the book *as of the
current time*. It returns the resulting event log, which can then be replayed
through a fresh engine any number of times (``simulation.replay``) so that
different analyses see an identical order-flow stream.

Seed policy: every run is driven by one ``numpy.random.default_rng(seed)``;
the same parameters, schedule and seed always reproduce the same event log.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol

import numpy as np

from src.events import Cancel, Event, LimitOrder, MarketOrder, Side
from src.matching_engine import MatchingEngine


@dataclass(frozen=True)
class OrderFlowParams:
    limit_rate: float = 1.0  # limit orders per second, per side
    market_rate: float = 0.20  # market orders per second, per side
    cancel_rate: float = 0.05  # per resting order, per second
    max_distance: int = 10  # ticks from the opposite best quote
    distance_alpha: float = 0.5  # P(d) proportional to d ** -alpha
    lot: int = 100  # shares per lot
    limit_max_lots: int = 5
    market_size_p: float = 0.4  # geometric parameter; mean lots = 1 / p
    initial_bid: int = 9_999  # ticks (e.g. $99.99 at a $0.01 tick)
    initial_ask: int = 10_001

    def distance_probs(self) -> np.ndarray:
        d = np.arange(1, self.max_distance + 1, dtype=float)
        w = d ** (-self.distance_alpha)
        return w / w.sum()


@dataclass(frozen=True)
class Rates:
    limit_buy: float
    limit_sell: float
    market_buy: float
    market_sell: float


class RateSchedule(Protocol):
    """Time-varying multipliers applied to the baseline rates."""

    def rates(self, t: float, base: OrderFlowParams) -> Rates: ...

    def breakpoints(self) -> list[float]: ...


class ConstantRates:
    def rates(self, t: float, base: OrderFlowParams) -> Rates:
        return Rates(base.limit_rate, base.limit_rate, base.market_rate, base.market_rate)

    def breakpoints(self) -> list[float]:
        return []


def generate_order_flow(
    params: OrderFlowParams,
    horizon: float,
    seed: int,
    schedule: RateSchedule | None = None,
) -> list[Event]:
    """Simulate the order-flow model on ``[0, horizon]`` and return the event log."""
    schedule = schedule or ConstantRates()
    rng = np.random.default_rng(seed)
    probs = params.distance_probs()
    cum_probs = np.cumsum(probs)
    breaks = sorted(b for b in schedule.breakpoints() if 0 < b < horizon)

    eng = MatchingEngine()
    book = eng.book
    events: list[Event] = []
    last_bid, last_ask = params.initial_bid, params.initial_ask
    next_id = 1
    t = 0.0
    bi = 0  # index of the next breakpoint

    while True:
        r = schedule.rates(t, params)
        n_resting = len(book)
        cancel_total = params.cancel_rate * n_resting
        total = r.limit_buy + r.limit_sell + r.market_buy + r.market_sell + cancel_total
        t_next = t + rng.exponential(1.0 / total)
        while bi < len(breaks) and breaks[bi] <= t:
            bi += 1
        if bi < len(breaks) and t_next >= breaks[bi]:
            t = breaks[bi]  # rates change here: restart the clocks (memoryless)
            bi += 1
            continue
        if t_next > horizon:
            break
        t = t_next

        bid, ask = book.best_bid(), book.best_ask()
        if bid is not None:
            last_bid = bid
        if ask is not None:
            last_ask = ask

        u = rng.random() * total
        if u < r.limit_buy + r.limit_sell:
            side = Side.BUY if u < r.limit_buy else Side.SELL
            d = int(np.searchsorted(cum_probs, rng.random(), side="right")) + 1
            d = min(d, params.max_distance)
            price = last_ask - d if side is Side.BUY else last_bid + d
            qty = params.lot * int(rng.integers(1, params.limit_max_lots + 1))
            ev: Event = LimitOrder(t, next_id, side, price, qty)
            next_id += 1
        elif u < r.limit_buy + r.limit_sell + r.market_buy + r.market_sell:
            side = Side.BUY if u < r.limit_buy + r.limit_sell + r.market_buy else Side.SELL
            qty = params.lot * int(rng.geometric(params.market_size_p))
            ev = MarketOrder(t, next_id, side, qty)
            next_id += 1
        else:
            ids = book.order_ids()
            ev = Cancel(t, ids[int(rng.integers(len(ids)))])

        eng.process(ev)
        events.append(ev)

    return events
